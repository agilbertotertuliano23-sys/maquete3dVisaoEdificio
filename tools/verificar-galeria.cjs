const { chromium } = require('C:/Users/agilb/AppData/Local/ms-playwright-go/1.61.1/package');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
(async () => {
 const browser = await chromium.launch({ headless: true });
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.resolve('assets/plantas/index.html')).href);
 await page.waitForFunction(()=>document.querySelectorAll('.card').length===26);
 await page.locator('.preview').first().click();
 await page.waitForFunction(()=>document.querySelector('#full-image').naturalWidth>0);
 await page.keyboard.press('ArrowRight');
 if(!(await page.locator('#light-title').textContent()).includes('AP-02'))throw Error('Navegação falhou');
 await page.keyboard.press('Escape');
 await page.locator('[data-view="ambientes.png"]').click();
 if(await page.locator('.card').count()!==26)throw Error('Painéis ausentes');
 await page.locator('[data-view="estrutura.png"]').click();
 if(await page.locator('.card').count()!==6)throw Error('Estruturas ausentes');
 await page.locator('[data-view="planta.png"]').click();
 await page.locator('#kind').selectOption('');
 await page.locator('#search').fill('Atelie');
 if(await page.locator('.card').count()!==1)throw Error('Busca falhou');
 await page.locator('#search').fill('');
 await page.screenshot({path:'assets/plantas/galeria-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Overflow mobile');
 await page.screenshot({path:'assets/plantas/galeria-mobile.png'});
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({cards:26,structures:6,consoleErrors:errors,mobile:'ok'}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
